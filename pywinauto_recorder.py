#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Launcher of Pywinauto Recorder, compiled by Nuitka into pywinauto_recorder.exe (see bin/Make_ALL.bat).

The application is in pywinauto_recorder/app.py. When the package is installed, it can also be started with the
command "pywinauto-recorder", or with "python -m pywinauto_recorder".

This launcher is not in the package: the compiled executable must remove the code generated by comtypes before
the package, and so pywinauto and comtypes, is imported.
"""

import os
import sys


def clear_comtypes_cache_after_update():
	"""
	Compiled Pywinauto Recorder only: the first time a new executable runs, it removes the code generated by comtypes.

	This code may have been generated by another version of comtypes, and the installer that updates
	Pywinauto Recorder does not remove it. It replaces "clear_comtypes_cache.exe -y" that the former installer ran.
	It must be called before pywinauto, and so comtypes, is imported.
	"""
	import shutil
	import sys
	import tempfile
	exe_path = os.path.abspath(sys.executable)
	try:
		exe_stat = os.stat(exe_path)
	except OSError:
		return
	stamp = exe_path + "|" + str(exe_stat.st_size) + "|" + str(int(exe_stat.st_mtime))
	stamp_dir = os.path.join(os.environ.get("LOCALAPPDATA") or os.path.expanduser("~"), "Pywinauto recorder")
	stamp_file = os.path.join(stamp_dir, "comtypes_cache_stamp.txt")
	try:
		with open(stamp_file, encoding="utf-8") as f:
			if f.read() == stamp:
				return  # this executable already removed the cache
	except OSError:
		pass
	python_version = str(sys.version_info[0]) + str(sys.version_info[1])
	exe_base_name = os.path.splitext(os.path.basename(exe_path))[0]
	cache_dirs = [  # the folders where comtypes may write the generated code (see comtypes.client._code_cache)
		os.path.join(os.path.dirname(exe_path), "comtypes", "gen"),
		os.path.join(os.environ.get("APPDATA", ""), "Python", "Python" + python_version, "comtypes_cache"),
		os.path.join(tempfile.gettempdir(), "comtypes_cache", exe_base_name + "-" + python_version)]
	for cache_dir in cache_dirs:
		if not os.path.isdir(cache_dir):
			continue
		for name in os.listdir(cache_dir):
			if name == "__init__.py":
				continue  # keep the comtypes.gen package
			path = os.path.join(cache_dir, name)
			try:
				if os.path.isdir(path):
					shutil.rmtree(path)
				else:
					os.remove(path)
			except OSError:
				pass
	try:
		os.makedirs(stamp_dir, exist_ok=True)
		with open(stamp_file, "w", encoding="utf-8") as f:
			f.write(stamp)
	except OSError:
		pass


if __name__ == '__main__':
	if "__compiled__" in globals():
		clear_comtypes_cache_after_update()
	from pywinauto_recorder.app import main
	sys.exit(main())
